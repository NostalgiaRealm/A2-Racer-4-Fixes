// run does the actual work. Every failure is reported, together with what it
// means for the game files, so the patcher never fails silently.
func run() bool {
	fmt.Println("A2 Racer 4 Fixes v" + patcherVersion)
	fmt.Println("--------------------------------")
	fmt.Println()

	if err := checkAdmin(); err != nil {
		fmt.Println("Error:", err)
		fmt.Println("Nothing was changed.")
		return false
	}

	reader := bufio.NewReader(os.Stdin)

	gameDir, err := askGameDir(reader)
	if err != nil {
		fmt.Println("Error:", err)
		fmt.Println("Nothing was changed.")
		return false
	}

	width, height, err := askResolution(reader)
	if err != nil {
		fmt.Println("Error:", err)
		fmt.Println("Nothing was changed.")
		return false
	}

	if err := patchInPlace(gameDir, width, height); err != nil {
		fmt.Println()
		fmt.Println("Patch failed:", err)
		return false
	}

	fmt.Println()
	if width == 0 {
		fmt.Printf("Created patched %s. The game now follows the resolution of your display.\n", gameFileName)
	} else {
		fmt.Printf("Created patched %s, fixed at %dx%d.\n", gameFileName, width, height)
	}
	fmt.Println("The crash, transparency, flicker and car physics fixes and the CD check")
	fmt.Println("removal are included.")
	fmt.Println()

	if err := restoreOverlays(gameDir); err != nil {
		fmt.Println()
		fmt.Println("Restoring the HUD files failed:", err)
		fmt.Println(gameFileName + " is patched, but the HUD will be misplaced.")
		fmt.Println("Fix the problem and run the patcher again.")
		return false
	}

	if err := patchMenu(gameDir); err != nil {
		fmt.Println()
		fmt.Println("Removing the CD check from "+menuFileName+" failed:", err)
		fmt.Println(gameFileName + " and the HUD files are patched, but the menu may still ask for the CD.")
		return false
	}

	fmt.Println()
	fmt.Println("Done. Original files were moved to the " + backupDir + " folder in:")
	fmt.Println("  " + gameDir)
	return true
}

// waitBeforeClosing keeps a console window that closes together with the
// patcher open, so the result can always be read.
func waitBeforeClosing() {
	if !consoleWillClose() {
		return
	}

	fmt.Println()
	fmt.Print("Press Enter to close.")
	_, _ = bufio.NewReader(os.Stdin).ReadString('\n')
}

// askGameDir asks for the game folder instead of assuming the current one,
// because installations differ, especially in Wine prefixes on Linux.
func askGameDir(reader *bufio.Reader) (string, error) {
	suggested := defaultGameDir()

	fmt.Println("Enter the A2 Racer 4 game folder (the folder that contains spel.dat).")
	fmt.Println("Press Enter to use this folder:")
	fmt.Println("  " + suggested)
	fmt.Print("Game folder: ")

	line, err := reader.ReadString('\n')
	if err != nil && len(line) == 0 {
		return "", err
	}

	dir := cleanPath(line)
	if dir == "" {
		dir = suggested
	}

	// Terminals on Linux often escape spaces and brackets when a folder is
	// dragged in, e.g. Program\ Files\ \(x86\).
	if _, err := os.Stat(dir); err != nil && runtime.GOOS != "windows" && strings.Contains(dir, `\`) {
		dir = filepath.Clean(regexp.MustCompile(`\\(.)`).ReplaceAllString(dir, "$1"))
	}

	info, err := os.Stat(dir)
	if err != nil || !info.IsDir() {
		return "", fmt.Errorf("%s is not a folder", dir)
	}

	if _, found := findFile(dir, gameFileName); !found {
		return "", fmt.Errorf("there is no %s in %s. Choose the A2 Racer 4 game folder", gameFileName, dir)
	}

	fmt.Println()
	return dir, nil
}

// defaultGameDir suggests the folder the patcher itself is in when spel.dat is
// there, since Windows does not always start programs that need administrator
// rights in their own folder. Otherwise it falls back to the current folder.
func defaultGameDir() string {
	var candidates []string

	if exe, err := os.Executable(); err == nil {
		if resolved, err := filepath.EvalSymlinks(exe); err == nil {
			exe = resolved
		}
		candidates = append(candidates, filepath.Dir(exe))
	}

	if current, err := os.Getwd(); err == nil {
		candidates = append(candidates, current)
	}

	for _, dir := range candidates {
		if _, found := findFile(dir, gameFileName); found {
			return dir
		}
	}

	if len(candidates) > 0 {
		return candidates[len(candidates)-1]
	}

	return "."
}

// writeVerified writes data and reads it back, so a write that silently did
// not happen, for example because a virus scanner undid it, is reported.
func writeVerified(path string, data []byte) error {
	if err := os.WriteFile(path, data, 0644); err != nil {
		return err
	}

	written, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("could not read %s back after writing: %v", path, err)
	}

	if !bytes.Equal(written, data) {
		return fmt.Errorf("%s does not contain the patched data after writing", path)
	}

	return nil
}

// cleanPath accepts a folder the way people tend to enter it: surrounded by
// quotes (drag and drop) or starting with ~ for the home folder.
func cleanPath(input string) string {
	path := strings.TrimSpace(input)

	if len(path) >= 2 && (path[0] == '"' || path[0] == '\'') && path[len(path)-1] == path[0] {
		path = path[1 : len(path)-1]
	}

	if path == "~" || strings.HasPrefix(path, "~/") {
		if home := userHomeDir(); home != "" {
			path = filepath.Join(home, path[1:])
		}
	}

	if path == "" {
		return ""
	}

	return filepath.Clean(path)
}

// userHomeDir returns the home folder, or "" when it is unknown.
func userHomeDir() string {
	if runtime.GOOS == "windows" {
		return os.Getenv("USERPROFILE")
	}

	return os.Getenv("HOME")
}

// findFile looks up name in dir ignoring case, so SPEL.DAT is found as well
// on case-sensitive Linux file systems. It only stats the matching name, so one
// unreadable file elsewhere in the folder cannot hide spel.dat.
func findFile(dir string, name string) (string, bool) {
	if f, err := os.Open(dir); err == nil {
		names, err := f.Readdirnames(-1)
		f.Close()
		if err == nil {
			sort.Strings(names)
			for _, entry := range names {
				if strings.EqualFold(entry, name) {
					path := filepath.Join(dir, entry)
					if info, err := os.Lstat(path); err != nil || !info.IsDir() {
						return path, true
					}
				}
			}
		}
	}

	return filepath.Join(dir, name), false
}

// backupPathFor returns where an original file is moved to. An existing
// backup is never overwritten, since it may hold the untouched 4:3 file.
func backupPathFor(gameDir string, name string) (string, error) {
	dir := filepath.Join(gameDir, backupDir)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return "", fmt.Errorf("could not create %s folder: %v", backupDir, err)
	}

	path := filepath.Join(dir, name)
	if _, err := os.Stat(path); err == nil {
		stamp := time.Now().Format("20060102_150405")
		ext := filepath.Ext(name)
		path = filepath.Join(dir, strings.TrimSuffix(name, ext)+"_"+stamp+ext)
	}

	return path, nil
}

// askResolution returns 0, 0 when the game should follow the display.
func askResolution(reader *bufio.Reader) (int, int, error) {
	fmt.Print("Press Enter to follow the resolution of your display, or type a fixed one such as 2560x1440: ")

	line, err := reader.ReadString('\n')
	if err != nil && len(line) == 0 {
		return 0, 0, err
	}

	line = strings.TrimSpace(line)
	if line == "" {
		return 0, 0, nil
	}

	re := regexp.MustCompile(`(?i)^\s*([0-9]{3,5})\s*x\s*([0-9]{3,5})\s*$`)
	matches := re.FindStringSubmatch(line)
	if matches == nil {
		return 0, 0, fmt.Errorf("invalid resolution format. Use something like 2560x1440")
	}

	width, err := strconv.Atoi(matches[1])
	if err != nil {
		return 0, 0, err
	}

	height, err := strconv.Atoi(matches[2])
	if err != nil {
		return 0, 0, err
	}

	if width <= 0 || height <= 0 || width > 65535 || height > 65535 {
		return 0, 0, fmt.Errorf("resolution values must be between 1 and 65535")
	}

	return width, height, nil
}

func patchInPlace(gameDir string, width int, height int) error {
	inputPath, _ := findFile(gameDir, gameFileName)

	// Everything up to moving the original happens before spel.dat is touched.
	unchanged := func(err error) error {
		return fmt.Errorf("%v. Nothing was changed", err)
	}

	data, err := os.ReadFile(inputPath)
	if err != nil {
		return unchanged(fmt.Errorf("could not read %s: %v", gameFileName, err))
	}

	if len(data) < 0x1B3932 {
		return unchanged(fmt.Errorf("%s is smaller than expected; wrong file?", gameFileName))
	}

	if len(data) < 2 || data[0] != 'M' || data[1] != 'Z' {
		return unchanged(fmt.Errorf("%s does not look like a Windows PE executable", gameFileName))
	}

	source := data
	if !patchCodeFits(source) {
		// An older version of this patch has other code in that place, so start from
		// the file it was made from.
		backup, hasBackup := findFile(filepath.Join(gameDir, backupDir), gameFileName)
		if !hasBackup {
			return unchanged(fmt.Errorf("%s has unknown code at 0x%X and %s holds no original to start from", gameFileName, patchCodeOffset, backupDir))
		}
		source, err = os.ReadFile(backup)
		if err != nil {
			return unchanged(fmt.Errorf("could not read %s: %v", backup, err))
		}
		if !patchCodeFits(source) {
			return unchanged(fmt.Errorf("%s and the copy in %s both have unknown code at 0x%X", gameFileName, backupDir, patchCodeOffset))
		}
	}

	patched := make([]byte, len(source))
	copy(patched, source)

	if err := applyPatch(patched, width, height); err != nil {
		return unchanged(err)
	}

	backupPath, err := backupPathFor(gameDir, filepath.Base(inputPath))
	if err != nil {
		return unchanged(err)
	}

	if err := os.Rename(inputPath, backupPath); err != nil {
		return unchanged(fmt.Errorf("could not move original %s to %s: %v", gameFileName, backupPath, err))
	}

	if err := writeVerified(inputPath, patched); err != nil {
		// Try to restore the original if writing fails.
		if restoreErr := os.Rename(backupPath, inputPath); restoreErr != nil {
			return fmt.Errorf("could not write patched %s: %v. The original is still in %s", gameFileName, err, backupPath)
		}
		return fmt.Errorf("could not write patched %s: %v. The original %s was put back", gameFileName, err, gameFileName)
	}

	return nil
}

// patchCodeFits says whether the added code can go into this file: the place for
// it is empty, or already holds this version of the code.
func patchCodeFits(data []byte) bool {
	size := len(spelPatchCode) - 8
	if len(data) < patchCodeOffset+size {
		return false
	}
	place := data[patchCodeOffset : patchCodeOffset+size]
	return bytes.Equal(place, spelPatchCode[:size]) || bytes.Equal(place, make([]byte, size))
}

// patchMenu removes the CD check from menu.exe. A file that already has the
// change is left alone, so running the patcher again keeps the original backup.
func patchMenu(gameDir string) error {
	inputPath, _ := findFile(gameDir, menuFileName)

	unchanged := func(err error) error {
		return fmt.Errorf("%v. %s was not changed", err, menuFileName)
	}

	data, err := os.ReadFile(inputPath)
	if err != nil {
		return unchanged(fmt.Errorf("could not read %s: %v", menuFileName, err))
	}

	if len(data) < menuCheckOffset+len(menuCheckOriginal) {
		return unchanged(fmt.Errorf("%s is smaller than expected; wrong file?", menuFileName))
	}

	current := data[menuCheckOffset : menuCheckOffset+len(menuCheckOriginal)]
	if bytes.Equal(current, menuCheckPatched) {
		return nil
	}
	if !bytes.Equal(current, menuCheckOriginal) {
		return unchanged(fmt.Errorf("bytes did not match expected original pattern at 0x%X. This may be the wrong %s version", menuCheckOffset, menuFileName))
	}
	copy(current, menuCheckPatched)

	backupPath, err := backupPathFor(gameDir, filepath.Base(inputPath))
	if err != nil {
		return unchanged(err)
	}

	if err := os.Rename(inputPath, backupPath); err != nil {
		return unchanged(fmt.Errorf("could not move original %s to %s: %v", menuFileName, backupPath, err))
	}

	if err := writeVerified(inputPath, data); err != nil {
		if restoreErr := os.Rename(backupPath, inputPath); restoreErr != nil {
			return fmt.Errorf("could not write patched %s: %v. The original is still in %s", menuFileName, err, backupPath)
		}
		return fmt.Errorf("could not write patched %s: %v. The original %s was put back", menuFileName, err, menuFileName)
	}

	return nil
}

// iniLine splits an overlay file line into its section name, or its key and the
// position of its value. Comments start with a semicolon.
func iniLine(line string) (section string, key string, valueStart int) {
	content := line
	if i := strings.Index(content, ";"); i >= 0 {
		content = content[:i]
	}

	trimmed := strings.TrimSpace(content)
	if strings.HasPrefix(trimmed, "[") {
		if end := strings.Index(trimmed, "]"); end > 0 {
			return trimmed[1:end], "", 0
		}
		return "", "", 0
	}

	equals := strings.Index(content, "=")
	if equals < 0 {
		return "", "", 0
	}

	valueStart = equals + 1
	for valueStart < len(content) && (content[valueStart] == ' ' || content[valueStart] == '\t') {
		valueStart++
	}
	return "", strings.ToLower(strings.TrimSpace(content[:equals])), valueStart
}

// isOriginalOverlay recognizes the game's own HUD layout. The game moves it to the
// screen edges by itself, so a file that an earlier patcher or a hand tuned HUD
// already moved would end up in the wrong place.
func isOriginalOverlay(data []byte) bool {
	section := ""
	found := 0
	for _, line := range strings.SplitAfter(string(data), "\n") {
		name, key, valueStart := iniLine(line)
		if name != "" {
			section = name
		} else if key == "position" {
			value := line[valueStart:]
			switch {
			case strings.EqualFold(section, "OVL_SPEEDOMETER_BODY"):
				if !strings.HasPrefix(value, "640,") {
					return false
				}
				found++
			case strings.EqualFold(section, "OVL_COMMUNICATOR_BODY"):
				if !strings.HasPrefix(value, "0,") {
					return false
				}
				found++
			}
		}
	}
	return found == 2
}

// originalOverlay finds the game's own version of an overlay file. The first
// backup holds it after an earlier run, otherwise it is still in the game folder.
func originalOverlay(gameDir string, name string) ([]byte, error) {
	backup, hasBackup := findFile(filepath.Join(gameDir, backupDir), name)
	target, exists := findFile(gameDir, name)

	if hasBackup {
		if data, err := os.ReadFile(backup); err != nil {
			return nil, fmt.Errorf("could not read %s: %v", backup, err)
		} else if isOriginalOverlay(data) {
			return data, nil
		}
	}

	if exists {
		if data, err := os.ReadFile(target); err != nil {
			return nil, fmt.Errorf("could not read %s: %v", target, err)
		} else if isOriginalOverlay(data) {
			return data, nil
		}
	}

	if !hasBackup && !exists {
		return nil, fmt.Errorf("there is no %s in %s", name, gameDir)
	}

	return nil, fmt.Errorf("no original %s found: it was changed by an older HUD fix. Restore it from the game CD and run the patcher again", name)
}

// restoreOverlays puts back the game's own overlay files where an older version
// of this patch changed them, and moves the changed files to the backup folder.
func restoreOverlays(gameDir string) error {
	for _, name := range overlayNames {
		target, exists := findFile(gameDir, name)

		// Only the "Schaduw" extra car update brings this one.
		if name == extraCarOverlay && !exists {
			continue
		}

		data, err := originalOverlay(gameDir, name)
		if err != nil {
			return err
		}

		backupPath := ""
		if exists {
			current, err := os.ReadFile(target)
			if err != nil {
				return fmt.Errorf("could not read %s: %v", target, err)
			}

			if bytes.Equal(current, data) {
				continue
			}

			backupPath, err = backupPathFor(gameDir, filepath.Base(target))
			if err != nil {
				return err
			}

			if err := os.Rename(target, backupPath); err != nil {
				return fmt.Errorf("could not move %s to %s: %v", name, backupPath, err)
			}
		}

		if err := writeVerified(target, data); err != nil {
			// Try to put the file back if writing fails.
			if backupPath != "" {
				if restoreErr := os.Rename(backupPath, target); restoreErr != nil {
					return fmt.Errorf("could not write %s: %v. The earlier file is still in %s", name, err, backupPath)
				}
			}
			return fmt.Errorf("could not write %s: %v", name, err)
		}

		fmt.Printf("Restored the original %s\n", name)
	}

	return nil
}

func applyPatch(data []byte, width int, height int) error {
	putU32 := func(offset int, value uint32) error {
		if offset < 0 || offset+4 > len(data) {
			return fmt.Errorf("offset 0x%X is outside the file", offset)
		}
		binary.LittleEndian.PutUint32(data[offset:offset+4], value)
		return nil
	}

	patchBytes := func(offset int, original []byte, replacement []byte, label string) error {
		if offset < 0 || offset+len(replacement) > len(data) {
			return fmt.Errorf("%s offset 0x%X is outside the file", label, offset)
		}

		current := data[offset : offset+len(replacement)]

		if bytes.Equal(current, replacement) {
			return nil // already patched
		}

		if !bytes.Equal(current, original) {
			return fmt.Errorf("%s bytes did not match expected original pattern at 0x%X. This may be the wrong spel.dat version", label, offset)
		}

		copy(current, replacement)
		return nil
	}

	// Everything that depends on the resolution is filled in at startup, in memory,
	// by the added code in spel_patch.asm: the display mode tables, the 4:3 reference
	// width at 0x00751F38 and the HUD positions. That reference width is 4:3 for the
	// output height. Examples: 1080 -> 1440, 1440 -> 1920, 2160 -> 2880.

	// Redirect viewport aspect division:
	// fidiv dword ptr ds:0x005B3798 -> fidiv dword ptr ds:0x00751F38
	if err := patchBytes(
		0x0C0E57,
		[]byte{0xDA, 0x35, 0x98, 0x37, 0x5B, 0x00},
		[]byte{0xDA, 0x35, 0x38, 0x1F, 0x75, 0x00},
		"aspect division",
	); err != nil {
		return err
	}

	// The game places the HUD with the real screen shape, which squashes it on
	// anything but 4:3. Use the 4:3 reference width there too, so the HUD keeps its
	// original proportions and height, including what the game places itself:
	// fidiv dword ptr ds:0x005B3798 -> fidiv dword ptr ds:0x00751F38 (HUD scale)
	if err := patchBytes(
		0x07CDD1,
		[]byte{0xDA, 0x35, 0x98, 0x37, 0x5B, 0x00},
		[]byte{0xDA, 0x35, 0x38, 0x1F, 0x75, 0x00},
		"HUD scale",
	); err != nil {
		return err
	}

	// fild dword ptr ds:0x005B3798 -> fild dword ptr ds:0x00751F38 (HUD position, twice)
	for _, offset := range []int{0x07FE55, 0x080534} {
		if err := patchBytes(
			offset,
			[]byte{0xDB, 0x05, 0x98, 0x37, 0x5B, 0x00},
			[]byte{0xDB, 0x05, 0x38, 0x1F, 0x75, 0x00},
			"HUD position",
		); err != nil {
			return err
		}
	}

	// The horizontal view for this screen shape comes from the added code too.
	// mov dword ptr [esi+0x14], -1.0 -> call set_horizontal_view
	// mov dword ptr [esi+0x1C], 2.0 -> nop. Older versions of this patch changed the
	// values in these instructions, so only the opcodes are checked.
	if !bytes.Equal(data[0x0C0E8A:0x0C0E8A+7], horizontalViewCall) {
		if !bytes.Equal(data[0x0C0E8A:0x0C0E8D], []byte{0xC7, 0x46, 0x14}) {
			return fmt.Errorf("horizontal view bytes did not match expected original pattern at 0xC0E8A. This may be the wrong spel.dat version")
		}
		copy(data[0x0C0E8A:], horizontalViewCall)
	}
	if !bytes.Equal(data[0x0C0E96:0x0C0E96+7], []byte{0x90, 0x90, 0x90, 0x90, 0x90, 0x90, 0x90}) {
		if !bytes.Equal(data[0x0C0E96:0x0C0E99], []byte{0xC7, 0x46, 0x1C}) {
			return fmt.Errorf("horizontal view bytes did not match expected original pattern at 0xC0E96. This may be the wrong spel.dat version")
		}
		copy(data[0x0C0E96:], []byte{0x90, 0x90, 0x90, 0x90, 0x90, 0x90, 0x90})
	}

	// Texture memory crash fix (not related to the resolution):
	// at race start the game measures texture memory by creating 256x256 video
	// memory textures until CreateSurface fails, keeping them in a 1024-entry
	// stack array. With more than ~128 MB of VRAM that array overflows and the
	// game crashes. Skip the probe and report 64 MB instead; the game still uses
	// min(custom_texture_memory, measured):
	// mov eax, 0x1000 / call 0x00559400 / push ebx -> mov dword ptr [ecx+0x2A1], 0x04000000 / ret
	if err := patchBytes(
		0x0BC0F0,
		[]byte{0xB8, 0x00, 0x10, 0x00, 0x00, 0xE8, 0x06, 0xD3, 0x09, 0x00, 0x53},
		[]byte{0xC7, 0x81, 0xA1, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0xC3},
		"texture memory probe",
	); err != nil {
		return err
	}

	// Transparency fix (not related to the resolution): the game marks transparent
	// texels with a color key on 16-bit textures, which shows as black around objects
	// on some current graphics drivers. Use the 1-bit alpha texture format instead,
	// clear alpha on transparent texels only, discard them with the alpha test and
	// turn the color key off.
	//
	// CD check removal: when no drive holds the game CD, the game carries on instead
	// of stopping with an error. All game files are in the game folder after
	// installing, and a CD that is present is still used as before.
	//
	// Both are in fixPatches, with the added code. The last two values of that code
	// are a fixed resolution, or 0 to follow the display.
	codeSize := len(spelPatchCode) - 8
	if err := patchBytes(patchCodeOffset, make([]byte, codeSize), spelPatchCode[:codeSize], "added code"); err != nil {
		return err
	}
	if err := putU32(patchCodeOffset+codeSize, uint32(width)); err != nil {
		return err
	}
	if err := putU32(patchCodeOffset+codeSize+4, uint32(height)); err != nil {
		return err
	}
	for _, p := range fixPatches {
		if err := patchBytes(p.offset, p.original, p.replacement, p.label); err != nil {
			return err
		}
	}

	return nil
}
