//go:build ignore
// +build ignore

// gen_overlays_legacy.go writes overlays_legacy.go, which holds the files in
// overlays/ as Go strings. Go older than 1.16 has no go:embed, and the 32-bit
// Windows version is built with Go 1.10. Run it before such a build:
//
//	go run gen_overlays_legacy.go
package main

import (
	"bytes"
	"fmt"
	"io/ioutil"
	"log"
	"path/filepath"
	"sort"
	"strconv"
)

const header = `// Code generated by gen_overlays_legacy.go. DO NOT EDIT.

//go:build !go1.16
// +build !go1.16

package main

import "fmt"

// overlayNames lists the built-in overlay files in name order.
func overlayNames() ([]string, error) {
	return legacyOverlayNames, nil
}

// overlayData returns the contents of a built-in overlay file.
func overlayData(name string) ([]byte, error) {
	data, ok := legacyOverlayData[name]
	if !ok {
		return nil, fmt.Errorf("unknown overlay file %s", name)
	}

	return []byte(data), nil
}

`

func main() {
	paths, err := filepath.Glob(filepath.Join("overlays", "*.ini"))
	if err != nil {
		log.Fatal(err)
	}
	if len(paths) == 0 {
		log.Fatal("no overlay files found: run this in the folder that contains overlays/")
	}
	sort.Strings(paths)

	var names, data bytes.Buffer
	for _, path := range paths {
		contents, err := ioutil.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}

		name := strconv.Quote(filepath.Base(path))
		fmt.Fprintf(&names, "\t%s,\n", name)
		fmt.Fprintf(&data, "\t%s: %s,\n", name, strconv.Quote(string(contents)))
	}

	var out bytes.Buffer
	out.WriteString(header)
	fmt.Fprintf(&out, "var legacyOverlayNames = []string{\n%s}\n\n", names.String())
	fmt.Fprintf(&out, "var legacyOverlayData = map[string]string{\n%s}\n", data.String())

	if err := ioutil.WriteFile("overlays_legacy.go", out.Bytes(), 0644); err != nil {
		log.Fatal(err)
	}
}
